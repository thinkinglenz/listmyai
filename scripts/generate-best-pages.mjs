// Turns the keyword research CSV into the page definitions behind /best/[slug].
//
//   node scripts/generate-best-pages.mjs
//
// The CSV is 2,000 rows but far fewer searches: most rows are the same query
// in a different word order ("ai tools for business 2026", "for business ai
// tools"). Google ranks one page per search, so rows are grouped by
// topic × audience × free, and every row still gets a page that targets it.

import fs from 'node:fs'

const SRC = 'data/seo/ai-keywords-2026.csv'
const OUT = 'src/lib/seo/best-pages.data.ts'

// Order matters: the first topic whose pattern appears in the keyword wins,
// so specific topics come before the catch-all.
const TOPICS = [
  ['ai-seo-tools', /\bseo\b/],
  ['ai-coding-tools', /\b(cod(e|ing)|programming|developer tools?)\b/],
  ['ai-image-generators', /\b(image|photo|art|picture|logo)\b/],
  ['ai-video-tools', /\bvideo\b/],
  ['ai-audio-tools', /\b(audio|voice|music|speech|podcast)\b/],
  ['ai-presentation-tools', /\b(presentation|slides?)\b/],
  ['ai-agents', /\bagents?\b/],
  ['ai-search-engines', /\bsearch\b/],
  ['ai-chatbots', /\b(chatbots?|chat)\b/],
  ['ai-marketing-tools', /\bmarketing\b/],
  ['ai-writing-tools', /\b(writ(ing|er)|content creation|copywriting|essay|blog)\b/],
  ['ai-productivity-tools', /\bproductivity\b/],
  ['ai-automation-tools', /\bautomation\b/],
  ['ai-education-tools', /\beducation\b/],
]
const CATEGORY_TOPIC = {
  'AI Writing': 'ai-writing-tools', 'AI Coding': 'ai-coding-tools', 'AI Chatbots': 'ai-chatbots',
  'AI Agents': 'ai-agents', 'AI Image': 'ai-image-generators', 'AI Search': 'ai-search-engines',
  'AI Audio': 'ai-audio-tools', 'AI Marketing': 'ai-marketing-tools', 'AI SEO': 'ai-seo-tools',
  'AI Video': 'ai-video-tools', 'AI Productivity': 'ai-productivity-tools',
  'AI Education': 'ai-education-tools', 'AI Presentations': 'ai-presentation-tools',
  'AI Automation': 'ai-automation-tools',
}
// Longest first so "small business" is not read as "business".
const AUDIENCES = ['small business', 'freelancers', 'students', 'startups', 'ecommerce', 'agencies',
  'professionals', 'teachers', 'beginners', 'developers', 'marketers', 'creators', 'entrepreneurs', 'business']
// Alternatives searches already have a page per tool at /alternatives/[slug].
const BRANDS = ['chatgpt', 'gemini', 'perplexity', 'claude', 'jasper', 'midjourney', 'copilot', 'grammarly', 'notion', 'canva', 'cursor']

function parseCsv(text) {
  const [head, ...lines] = text.trim().split(/\r?\n/)
  const cols = head.split(',')
  return lines.map(l => Object.fromEntries(l.split(',').map((v, i) => [cols[i], v])))
}

function audienceOf(k) {
  // The audience is whatever follows the last "for"; the rows include
  // garbled combinations such as "ai tools for business for students".
  const tail = k.includes(' for ') ? k.slice(k.lastIndexOf(' for ')) : k
  return AUDIENCES.find(a => new RegExp(`\\b${a}\\b`).test(tail))
    ?? AUDIENCES.find(a => new RegExp(`\\b${a}\\b`).test(k)) ?? null
}

const rows = parseCsv(fs.readFileSync(SRC, 'utf8'))
const pages = new Map()
const alternatives = new Map()

for (const r of rows) {
  const k = r.Keyword.toLowerCase().trim()
  const volume = Number(r['Estimated Monthly Searches']) || 0
  const audience = audienceOf(k)
  const brand = BRANDS.find(b => new RegExp(`\\b${b}\\b`).test(k) && k.includes('alternative'))
  if (brand) {
    const a = alternatives.get(brand) ?? { brand, keywords: [], audiences: new Set() }
    a.keywords.push(k); if (audience) a.audiences.add(audience)
    alternatives.set(brand, a)
    continue
  }
  // "ai tools for marketing" is a topic, not an audience, so the text is read
  // before the spreadsheet's category.
  const topic = TOPICS.find(([, re]) => re.test(k))?.[0] ?? CATEGORY_TOPIC[r.Category] ?? 'ai-tools'
  const free = /\bfree\b/.test(k)
  const slug = `${free ? 'free-' : ''}${topic}${audience ? `-for-${audience.replace(/ /g, '-')}` : ''}`
  const p = pages.get(slug) ?? { slug, topic, audience, free, volume: 0, keywords: [] }
  p.volume += volume
  p.keywords.push({ k, v: volume })
  pages.set(slug, p)
}

const list = [...pages.values()]
  .map(p => ({ ...p, keywords: p.keywords.sort((a, b) => b.v - a.v).map(x => x.k) }))
  .sort((a, b) => b.volume - a.volume)

const alts = [...alternatives.values()]
  .map(a => ({ brand: a.brand, audiences: [...a.audiences].sort(), keywords: a.keywords }))

const body = `// GENERATED by scripts/generate-best-pages.mjs from data/seo/ai-keywords-2026.csv.
// Do not edit by hand — change the script or the CSV and regenerate.

export interface BestPageDef {
  slug: string
  topic: string
  audience: string | null
  free: boolean
  /** Summed estimate from the research file. Relative order only. */
  volume: number
  /** Every research keyword this page targets, highest estimate first. */
  keywords: string[]
}

export const BEST_PAGES: BestPageDef[] = ${JSON.stringify(list, null, 2)}

export const ALTERNATIVE_TARGETS: { brand: string; audiences: string[]; keywords: string[] }[] = ${JSON.stringify(alts, null, 2)}
`
fs.writeFileSync(OUT, body)
const covered = list.reduce((s, p) => s + p.keywords.length, 0) + alts.reduce((s, a) => s + a.keywords.length, 0)
console.log(`${rows.length} keywords -> ${list.length} /best pages + ${alts.length} alternatives pages; covered ${covered}`)
console.log('top 20:', list.slice(0, 20).map(p => `${p.slug} (${p.keywords.length})`).join(', '))
